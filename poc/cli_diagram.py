"""Generate the two diagrams the capstone asks for, from the code itself.

    python -m poc.cli_diagram

Writes `docs/graph.md` and `docs/erd.md`. Both are derived, never hand-drawn:
the graph comes off the compiled LangGraph app, the ERD off a live SQLite
schema. A hand-drawn diagram is wrong the moment someone adds a column; these
are wrong only if the code is.

Mermaid is emitted as text rather than PNG on purpose. `draw_mermaid_png()`
needs headless Chromium or a call to mermaid.ink, and the POC's offline
guarantee (tests/test_offline.py) is worth more than a rendered image. GitHub,
VS Code and the artifact renderer all draw these fences natively.
"""

from __future__ import annotations

import sqlite3
import tempfile
from pathlib import Path

from langgraph.checkpoint.memory import InMemorySaver

from . import config, store
from .graph.build import build_graph

BANNER = "<!-- Generated by `python -m poc.cli_diagram`. Do not edit by hand. -->"

# Which side of the confidentiality boundary each table sits on. Stated here
# rather than inferred, because it is a design decision, not a schema fact.
BOUNDARY = {
    "ballot":          ("pseudonymous", "One reviewer's submission. Holds no identity column; `ballot_id` is the handle the identity side resolves."),
    "likert_answer":   ("pseudonymous", "Scores, keyed only by ballot."),
    "open_answer":     ("pseudonymous", "Free text **as written**. Masked at render time for the subject's copy, not on the way in."),
    "declined_item":   ("pseudonymous", "Items a reviewer marked \"not observed\". Records that no rating exists, never a score."),
    "guardrail_event": ("pseudonymous", "Code and timestamp only. Never the text that triggered it."),
    "subject":         ("attributable", "Who is being reviewed. Named on every report by design."),
    "self_assessment": ("attributable", "The subject's own ratings. Excluded from every aggregate."),
    "round_freeze":    ("operational", "Immutable digest taken when the window closes."),
}

NODE_NOTES = {
    "next_question": "Decides what to ask. Pure Python; writes the question into state before the graph suspends.",
    "collect": "Receives one answer: guardrails, then redaction *scoring* (the text is kept as written), then the specificity judge. Routing off the verdict is `if`, never the model.",
    "finish": "Terminal. The only node that writes to the response store, and only on consent + submit.",
}


def graph_markdown() -> str:
    app = build_graph(InMemorySaver())
    mermaid = app.get_graph().draw_mermaid()

    lines = [
        BANNER, "",
        "# Conversation engine — compiled graph", "",
        "Emitted from the compiled LangGraph app, so it cannot drift from the code.", "",
        "```mermaid", mermaid.strip(), "```", "",
        "**Solid** edges are unconditional; **dotted** edges are conditional.", "",
        "| Node | What it does |", "|---|---|",
    ]
    lines += [f"| `{n}` | {note} |" for n, note in NODE_NOTES.items()]
    lines += [
        "",
        "The two-node loop is deliberate: one rater turn per node invocation means "
        "every turn produces its own checkpoint, which is what makes save-and-resume "
        "exact rather than approximate. `thread_id` is the ballot id.",
        "",
    ]
    return "\n".join(lines)


def _schema(path: Path) -> tuple[dict[str, list[tuple]], list[tuple[str, str, str]]]:
    """Returns ({table: [(name, type, pk, notnull)]}, [(child, parent, column)])."""
    with sqlite3.connect(path) as conn:
        conn.row_factory = sqlite3.Row
        tables = [r[0] for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
        )]
        columns, edges = {}, []
        for table in tables:
            columns[table] = [
                (r["name"], (r["type"] or "TEXT").split("(")[0], bool(r["pk"]), bool(r["notnull"]))
                for r in conn.execute(f"PRAGMA table_info({table})")
            ]
            for r in conn.execute(f"PRAGMA foreign_key_list({table})"):
                edges.append((table, r["table"], r["from"]))
    return columns, edges


def erd_markdown() -> str:
    # Build a throwaway database so the ERD reflects the schema, not whatever
    # data happens to be lying around.
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "schema.db"
        store.init(path)
        columns, edges = _schema(path)

    lines = [BANNER, "", "# Data model", "",
             "Derived from a freshly initialised database, so it tracks `poc/store.py`.", "",
             "```mermaid", "erDiagram"]

    for child, parent, _col in sorted(set(edges)):
        lines.append(f"    {parent} ||--o{{ {child} : has")

    for table, cols in columns.items():
        lines.append(f"    {table} {{")
        for name, ctype, pk, notnull in cols:
            marker = " PK" if pk else ""
            if not pk and any(e[0] == table and e[2] == name for e in edges):
                marker = " FK"
            comment = "" if (pk or notnull) else ' "nullable"'
            lines.append(f"        {ctype} {name}{marker}{comment}")
        lines.append("    }")
    lines += ["```", "",
              "## Which side of the boundary", "",
              "| Table | Side | Why |", "|---|---|---|"]

    for table in columns:
        side, why = BOUNDARY.get(table, ("unclassified", "**Not classified — add it to `BOUNDARY` in poc/cli_diagram.py.**"))
        label = {"pseudonymous": "🔑 pseudonymous — resolvable by HR",
                 "attributable": "👤 attributable by design",
                 "operational": "⚙️ operational"}.get(side, "❓ unclassified")
        lines.append(f"| `{table}` | {label} | {why} |")

    lines += [
        "",
        "## Where identity lives, and who can resolve it",
        "",
        "**No table above carries a reviewer's name, email, role or relationship.** The "
        "response store is pseudonymous: every row hangs off a `ballot_id` and nothing "
        "more. `tests/test_identity_separation.py` asserts that against the live schema, "
        "so adding such a column later fails the build rather than leaking quietly.",
        "",
        "**But pseudonymous is not anonymous, and this round does not pretend otherwise.** "
        "Following the client's demo-2 clarification, HR administers the round and is "
        "entitled to see who reviewed whom and what they wrote. The mapping "
        "`ballot_id -> reviewer` lives on the identity side — `data/invites.json` in this "
        "POC, `identity.db` in the full build — and `app.rounds.rater_labels()` is the one "
        "function that resolves it. `poc.reporting` never looks it up; a caller holding "
        "both halves passes it in. So every attribution path is one somebody wrote on "
        "purpose, and a leak of this database alone still discloses no reviewer.",
        "",
        "**What the split still buys, now that HR can attribute:**",
        "",
        "* A reviewer's team, role and relationship never travel with the response, so "
        "even the HR copy cannot be broken down by role — the brief's requirement, and "
        "the one part of it this change leaves intact.",
        "* The subject's copy is rendered from the same rows with masking applied and no "
        "attribution, so what protects the reviewer is a render decision that is tested, "
        "not a hope about who opens which file.",
        "",
        "## What the subject's copy does NOT contain",
        "",
        "`open_answer.text` holds the sentence as the reviewer typed it. Masking runs on "
        "the way *out*, in `poc.reporting`, keyed on audience — `AUDIENCE_SUBJECT` strips "
        "names, contact details and role-disclosing phrases and attributes nothing; "
        "`AUDIENCE_HR` does neither. The default is `AUDIENCE_SUBJECT`, so a caller that "
        "forgets to say who is reading gets the protective rendering.",
        "",
        "The cost of moving masking out of the write path, stated plainly: a raw answer "
        "now reaches disk, where previously it could not. The 12-month raw-retention rule "
        "in `reporting-rules.yaml` is what bounds that, and it is now doing real work "
        "rather than describing rows that were already scrubbed.",
        "",
        "The self-assessment sits in its own table rather than as a flagged ballot. Marking "
        "one ballot in a pool of two or three as \"the self one\" would identify the remaining "
        "reviewers by elimination, so the response pool never carries a role marker at all.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    out = config.ROOT / "docs"
    out.mkdir(exist_ok=True)
    for name, text in (("graph.md", graph_markdown()), ("erd.md", erd_markdown())):
        (out / name).write_text(text, encoding="utf-8")
        print(f"wrote docs/{name}")


if __name__ == "__main__":
    main()
